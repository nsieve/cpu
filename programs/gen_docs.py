# GENERATES THE CONTROL BITS AND MICROCODE DOCS FROM crom_programmer.py
# writes notes/opcodes&microinstructions/controlbits.md and instructionset_extended.md
# instruction names come from isa.md, and it warns if isa.md and the microcode don't match

import re
from pathlib import Path

import crom_programmer as cp

HERE = Path(__file__).resolve().parent
NOTES = HERE.parent / "notes" / "opcodes&microinstructions"
ISA_FILE = NOTES / "isa.md"
CONTROLBITS_FILE = NOTES / "controlbits.md"
EXTENDED_FILE = NOTES / "instructionset_extended.md"

GENERATED_NOTE = ("Generated by `programs/gen_docs.py`.")

MAX_STEPS = 16
FLAG_COMBOS = range(16)   # bit 0 = Z, bit 1 = C, bit 2 = N, bit 3 = V (same order as the EPROM address)

# conditions used to describe a step that changes with the flags
CONDITIONS = {
    "C":  lambda f: bool(f & 0b0010),
    "NC": lambda f: not f & 0b0010,
    "Z":  lambda f: bool(f & 0b0001),
    "NZ": lambda f: not f & 0b0001,
    "N":  lambda f: bool(f & 0b0100),
    "NN": lambda f: not f & 0b0100,
    "V":  lambda f: bool(f & 0b1000),
    "NV": lambda f: not f & 0b1000,
}


def read_control_bits():
    # NAME = number  # description, from the CONTROL BITS section of crom_programmer.py
    bits = {}
    source = (HERE / "crom_programmer.py").read_text()
    for line in source.splitlines():
        m = re.match(r"^(\w+)\s*=\s*(\d+)\s*#\s*(.*)$", line)
        if m and int(m.group(2)) < 48:
            bits[int(m.group(2))] = (m.group(1), m.group(3).strip())
    return bits


def read_isa():
    # (base opcode, subOp or None, mnemonic, cycles) from the instructions table of isa.md
    instructions = []
    for line in ISA_FILE.read_text().splitlines():
        cols = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]   # skip escaped \|
        if len(cols) < 6 or not cols[1].startswith("0x"):
            continue
        base = int(cols[1], 16)
        sub = None if cols[2] == "-" else int(cols[2], 16)
        cycles = {int(x) for x in re.findall(r"\d+", cols[5])}
        instructions.append((base, sub, cols[0], cycles))
    return instructions


def control_word(eproms, base, sub, step, flags):
    addr = (base << 3) | sub | (step << 8) | (flags << 12)
    e1, e2, e3 = eproms
    word = e1[addr] | (e2[addr] << 16) | (e3[addr] << 32)
    return word ^ cp.active_low_mask   # 1 = the signal is active, whatever its level


def ends(word):
    # the instruction ends with nMPC_RST, or freezes there with nHALT (HALT)
    return (word >> cp.nMPC_RST) & 1 or (word >> cp.nHALT) & 1


def run_instruction(eproms, base, sub):
    # list of steps, each one a dict {flags: control word} with only the flag combos still running
    steps = []
    running = set(FLAG_COMBOS)
    for step in range(MAX_STEPS):
        if not running:
            break
        words = {f: control_word(eproms, base, sub, step, f) for f in running}
        steps.append(words)
        running = {f for f in running if not ends(words[f])}
    return steps


def cycle_counts(steps):
    counts = set()
    for i, words in enumerate(steps):
        counts |= {i + 1 for w in words.values() if ends(w)}
    return counts


def bit_names(word, bits):
    return ", ".join(f"`{bits[b][0]}`" for b in sorted(bits) if (word >> b) & 1)


def describe_step(words, bits):
    groups = {}
    for f, w in words.items():
        groups.setdefault(w, set()).add(f)
    if len(groups) == 1:
        return bit_names(next(iter(groups)), bits)

    if len(groups) == 2:
        (w_a, f_a), (w_b, f_b) = groups.items()
        for name, cond in CONDITIONS.items():
            if all(cond(f) for f in f_a) and not any(cond(f) for f in f_b):
                common = w_a & w_b
                opposite = name[1:] if len(name) == 2 else "N" + name
                cases = sorted([(name, w_a & ~common), (opposite, w_b & ~common)],
                               key=lambda c: list(CONDITIONS).index(c[0]))   # always C before NC
                lines = [bit_names(common, bits)] if common else []
                lines += [f"if {cond}: {bit_names(extra, bits)}" for cond, extra in cases if extra]
                return "<br>".join(lines)

    # fallback, one line per flag combo
    return "<br>".join(f"ZCNV={f:04b}: {bit_names(w, bits)}" for f, w in sorted(words.items()))


def step_table(steps, bits):
    rows = ["| Step | Control bits |", "| ---- | ------------ |"]
    for i, words in enumerate(steps):
        frozen = " (the micro-PC stays in this step)" if any((w >> cp.nHALT) & 1 for w in words.values()) else ""
        rows.append(f"| {i} | {describe_step(words, bits)}{frozen} |")
    return rows


def check(eproms, isa, warnings):
    covered = set()
    for base, sub, name, cycles in isa:
        subs = range(8) if sub is None else [sub]
        covered |= {(base, s) for s in subs}

        if sub is None:
            first = run_instruction(eproms, base, 0)
            if any(run_instruction(eproms, base, s) != first for s in range(1, 8)):
                warnings.append(f"{name}: isa.md has no subOp, but the microcode changes with [10:8]")

        real = cycle_counts(run_instruction(eproms, base, subs[0]))
        if real != cycles:
            warnings.append(f"{name}: isa.md says {sorted(cycles)} cycles, the microcode takes {sorted(real)}")

    for base in range(32):
        for sub in range(8):
            if (base, sub) in covered:
                continue
            if (base, sub) not in cp.FREE_SLOTS:
                warnings.append(f"opcode 0x{base:02X} subOp {sub} is not in isa.md or FREE_SLOTS")
            elif cycle_counts(run_instruction(eproms, base, sub)) != {2}:
                warnings.append(f"free slot 0x{base:02X} subOp {sub} doesn't work as a 2-cycle NOP")


def write_controlbits(bits):
    lines = [
        "# Control Bits",
        "",
        GENERATED_NOTE,
        "",
        f"The control unit has 3 EPROMs with 16 outputs each, so 48 control bits, but only {len(bits)} are used. "
        "Bit 0 is output D0 of EPROM 1, bit 16 is D0 of EPROM 2, and bit 32 is D0 of EPROM 3.",
        "",
        "Bits that start with `n` are active-low. The programmer writes every bit inactive by default "
        "(1 for active-low, 0 for active-high), so an instruction only has to list the bits it uses.",
        "",
        "| Bit | Name | EPROM | Pin | Active | Description |",
        "| --- | ---- | ----- | --- | ------ | ----------- |",
    ]
    for b in range(48):
        eprom, pin = b // 16 + 1, f"D{b % 16}"
        if b in bits:
            name, desc = bits[b]
            level = "low" if (cp.active_low_mask >> b) & 1 else "high"
            lines.append(f"| {b} | `{name}` | {eprom} | {pin} | {level} | {desc} |")
        else:
            lines.append(f"| {b} | - | {eprom} | {pin} | - | unused |")
    CONTROLBITS_FILE.write_text("\n".join(lines) + "\n")


def write_extended(eproms, isa, bits):
    lines = [
        "# Instruction Set (Extended)",
        "",
        GENERATED_NOTE,
        "",
        "These are the control bits each instruction activates in every microstep. "
        "A bit in the list means the signal is active, so for an active-low bit (`n...`) it means the EPROM outputs a 0. "
        "The names and bits are in `controlbits.md`, and the summary of every instruction is in `isa.md`.",
        "",
        "Step 0 is the fetch, and it's the same in every instruction. "
        "When a step depends on the flags, the bits are split by condition, for example `if C:`. "
        "Instructions without a subOp use bits `[10:8]` as a register, so their microcode is the same for all 8 values.",
        "",
    ]
    for base, sub, name, _ in isa:
        opcode = f"0x{base:02X}" if sub is None else f"0x{base:02X} subOp 0x{sub:X}"
        steps = run_instruction(eproms, base, 0 if sub is None else sub)
        lines.append(f"### {opcode} --> {name}")
        lines.append("")
        lines += step_table(steps, bits)
        lines.append("")
    EXTENDED_FILE.write_text("\n".join(lines))


if __name__ == "__main__":
    eproms = cp.gen_microcode()
    bits = read_control_bits()
    isa = read_isa()

    write_controlbits(bits)
    write_extended(eproms, isa, bits)
    print(f"wrote {CONTROLBITS_FILE.name} ({len(bits)} control bits) "
          f"and {EXTENDED_FILE.name} ({len(isa)} instructions)")

    warnings = []
    check(eproms, isa, warnings)
    for w in warnings:
        print("WARNING:", w)
